/**
 * Named code groups the rules DSL refers to (`codeInGroup`). Codes only, never descriptions
 * (CLAUDE.md rule 11). Groups are data; tenants extend them through rules, not code changes.
 */
const range = (from: number, to: number) => Array.from({ length: to - from + 1 }, (_, i) => String(from + i));

